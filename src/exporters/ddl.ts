/**
 * ANSI SQL DDL for the three zones:
 *   raw        as landed: source names, text columns sized to the source
 *   curated    target names and types, NOT NULL, primary key, comments
 *   analytics  a view over curated that leaves out PII/PCI columns until a
 *              masking policy is approved (F12 replaces this with masked columns)
 */
import type { ColumnSpec, FileSpec } from '../domain/spec';
import { formatType } from '../spec/edit';
import { quoteIdent, sqlString, sqlType } from './sql-types';

const sensitive = (c: ColumnSpec) => c.pii.value !== null && c.pii.value.classification !== 'NONE';
const byPos = (s: FileSpec) => [...s.columns].sort((a, b) => a.position - b.position);

function rawTable(s: FileSpec): string {
  const cols = byPos(s).map((c) => `  ${quoteIdent(c.sourceName)} VARCHAR(${Math.max(1, c.profile.maxLength ?? 1) * 2})`);
  return `CREATE TABLE raw.${s.tableName.value} (\n${cols.join(',\n')}\n);`;
}

function curatedTable(s: FileSpec): string {
  const cols = byPos(s);
  const defs = cols.map((c) => {
    const { sql, tbd } = sqlType(c.type.value);
    const notNull = c.nullable.value === false ? ' NOT NULL' : '';
    return `  ${c.targetName.value} ${sql}${notNull}${tbd ? ' /* TBD: type not decided */' : ''}`;
  });
  const pk = cols.find((c) => c.primaryKey.value);
  if (pk) defs.push(`  CONSTRAINT pk_${s.tableName.value} PRIMARY KEY (${pk.targetName.value})`);
  const comments = cols
    .filter((c) => c.description.value)
    .map((c) => `COMMENT ON COLUMN curated.${s.tableName.value}.${c.targetName.value} IS ${sqlString(c.description.value ?? '')};`);
  return [`CREATE TABLE curated.${s.tableName.value} (\n${defs.join(',\n')}\n);`, ...comments].join('\n');
}

function analyticsView(s: FileSpec): string {
  const cols = byPos(s);
  const kept = cols.filter((c) => !sensitive(c));
  const left = cols.filter(sensitive).map((c) => `${c.targetName.value} (${c.pii.value?.classification} ${c.pii.value?.category ?? ''})`.trim());
  const note = left.length ? `-- Left out until a masking policy is approved: ${left.join(', ')}\n` : '';
  const select = kept.length ? kept.map((c) => `  ${c.targetName.value}`).join(',\n') : '  1 AS no_public_columns';
  return `${note}CREATE VIEW analytics.${s.tableName.value} AS\nSELECT\n${select}\nFROM curated.${s.tableName.value};`;
}

export function ddlExport(feedName: string, files: FileSpec[]): string {
  const sorted = [...files].sort((a, b) => a.fileName.localeCompare(b.fileName));
  const header = [
    `-- ${feedName}: target DDL generated by SpecSmith from the feed spec.`,
    '-- ANSI SQL; adjust types for your warehouse. Columns marked TBD still need a decision.',
    '',
    'CREATE SCHEMA IF NOT EXISTS raw;',
    'CREATE SCHEMA IF NOT EXISTS curated;',
    'CREATE SCHEMA IF NOT EXISTS analytics;',
  ];
  const sections = sorted.map((s) =>
    [
      `-- ${'='.repeat(70)}`,
      `-- ${s.tableName.value} (source file ${s.fileName}, ${s.columns.length} columns)`,
      `-- Types: ${byPos(s).map((c) => `${c.targetName.value}=${formatType(c.type.value)}`).join(', ')}`.slice(0, 400),
      rawTable(s),
      '',
      curatedTable(s),
      '',
      analyticsView(s),
    ].join('\n'),
  );
  return `${[...header, '', ...sections].join('\n')}\n`;
}
