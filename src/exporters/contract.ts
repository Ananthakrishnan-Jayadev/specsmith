/**
 * Data contract in the Open Data Contract Standard (ODCS) v3 layout.
 * Classification and provenance come straight from the spec.
 */
import type { FileSpec, LogicalType } from '../domain/spec';
import { sqlType } from './sql-types';
import { toYaml, type YamlValue } from './yaml';

const LOGICAL: Record<LogicalType, string> = {
  integer: 'integer', decimal: 'number', date: 'date', timestamp: 'date', boolean: 'boolean', string: 'string',
};

export function contractExport(feedId: string, feedName: string, files: FileSpec[]): string {
  const schema = [...files]
    .sort((a, b) => a.fileName.localeCompare(b.fileName))
    .map((s): YamlValue => ({
      name: s.tableName.value,
      physicalName: `curated.${s.tableName.value}`,
      logicalType: 'object',
      description: `From source file ${s.fileName}.`,
      properties: [...s.columns]
        .sort((a, b) => a.position - b.position)
        .map((c): YamlValue => ({
          name: c.targetName.value,
          logicalType: c.type.value ? LOGICAL[c.type.value.type] : 'string',
          physicalType: sqlType(c.type.value).sql,
          required: c.nullable.value === false,
          primaryKey: c.primaryKey.value || undefined,
          classification: c.pii.value ? (c.pii.value.classification === 'NONE' ? 'public' : c.pii.value.classification.toLowerCase()) : 'tbd',
          description: c.description.value ?? 'TBD',
          customProperties: [
            { property: 'sourceColumn', value: c.sourceName },
            ...(c.pii.value?.category ? [{ property: 'sensitiveCategory', value: c.pii.value.category }] : []),
          ],
        })),
    }));
  return `# Generated by SpecSmith (ODCS v3 layout). Status stays "draft" until the spec is signed off.\n${toYaml({
    apiVersion: 'v3.0.2',
    kind: 'DataContract',
    id: `specsmith-${feedId}`,
    name: feedName,
    version: '1.0.0',
    status: 'draft',
    description: { purpose: `Column-level contract for the ${feedName} feed.` },
    schema,
  })}`;
}
