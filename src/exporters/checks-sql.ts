/** One query per rule-decided check; each returns the rows that VIOLATE it (empty = pass). */
import type { FileSpec } from '../domain/spec';
import { checksForFeed, type Check } from '../rules/checks';
import type { Relationship } from '../domain/relationship';
import { sqlString } from './sql-types';

function query(c: Check): string {
  const t = `curated.${c.table}`;
  switch (c.type) {
    case 'notNull': return `SELECT * FROM ${t} WHERE ${c.column} IS NULL;`;
    case 'unique': return `SELECT ${c.column}, COUNT(*) AS occurrences FROM ${t} GROUP BY ${c.column} HAVING COUNT(*) > 1;`;
    case 'maxLength': return `SELECT * FROM ${t} WHERE LENGTH(${c.column}) > ${c.length};`;
    case 'acceptedValues': return `SELECT * FROM ${t} WHERE ${c.column} IS NOT NULL AND ${c.column} NOT IN (${(c.values ?? []).map(sqlString).join(', ')});`;
    case 'fkPresent': return `SELECT f.* FROM ${t} f LEFT JOIN curated.${c.refTable} p ON f.${c.column} = p.${c.refColumn} WHERE f.${c.column} IS NOT NULL AND p.${c.refColumn} IS NULL;`;
  }
}

export function checksSqlExport(feedName: string, files: FileSpec[], rels: Relationship[] = []): string {
  const checks = checksForFeed(files, rels);
  const body = checks.map((c) => `-- ${c.id}: ${c.table}.${c.column}, expected ${c.expected}\n${query(c)}`);
  return `-- ${feedName}: ${checks.length} data checks generated by SpecSmith.\n-- Each query returns the rows that violate the check; an empty result means it passed.\n\n${body.join('\n\n')}\n`;
}
