/**
 * Confluence pages for a feed spec. Output is deterministic (no timestamps),
 * so an unchanged spec renders byte-identical and the Gatekeeper can skip it.
 */
import type { ColumnSpec, FieldValue, FileSpec } from '../domain/spec';
import { formatType, specStats } from '../spec/edit';
import { COLOURS, attachmentLink, bulletList, childrenMacro, escapeXml, externalLink, heading, infoPanel, paragraph, table, type Cell } from './storage';

export const parentTitle = (feedName: string) => `${feedName}: Feed Spec`;
export const fileTitle = (feedName: string, spec: FileSpec) => `${feedName}: ${spec.tableName.value}`;

/** Colour by provenance: TBD yellow, rule-derived grey, AI purple, human/config none. */
function colourFor(f: FieldValue<unknown>): string | undefined {
  switch (f.source) {
    case 'tbd': return COLOURS.yellow;
    case 'derived': return COLOURS.grey;
    case 'ai': return COLOURS.purple;
    default: return undefined;
  }
}

function cell<T>(f: FieldValue<T>, show: (v: T) => string, code = false): Cell {
  const text = f.source === 'tbd' && f.value === null ? 'TBD' : show(f.value);
  const c = colourFor(f);
  return { text, ...(c ? { highlight: c } : {}), ...(code ? { code } : {}) };
}

const legend = () =>
  table(
    ['Colour', 'Meaning'],
    [
      [{ text: 'Yellow', highlight: COLOURS.yellow }, { text: 'TBD: not decided yet; needs a reviewer.' }],
      [{ text: 'Grey', highlight: COLOURS.grey }, { text: 'Derived by SpecSmith rules from the data; not yet confirmed by a person.' }],
      [{ text: 'Purple', highlight: COLOURS.purple }, { text: 'Suggested by an AI agent and accepted by a reviewer.' }],
      [{ text: 'No colour' }, { text: 'Set or confirmed by a person, or by site configuration.' }],
    ],
  );

const notice = () =>
  infoPanel(paragraph('This page is generated by SpecSmith. Make changes in the SpecSmith app and publish again. Direct edits here will block the next publish so they are not silently overwritten.'));

export interface Delivery {
  epicKey: string;
  epicUrl?: string;
}

export interface ExportRef {
  name: string;
  description: string;
}

export function renderParentPage(feedName: string, files: FileSpec[], delivery?: Delivery, exports: ExportRef[] = []): string {
  const sorted = [...files].sort((a, b) => a.fileName.localeCompare(b.fileName));
  const rows = sorted.map((f): Cell[] => {
    const st = specStats(f);
    return [
      { text: f.fileName, code: true },
      { text: f.tableName.value, code: true },
      { text: f.rowCount.toLocaleString('en-US') },
      { text: String(st.columns) },
      { text: String(st.tbd), ...(st.tbd > 0 ? { highlight: COLOURS.yellow } : {}) },
      { text: String(st.pii) },
      { text: String(st.pci) },
      { text: String(st.errors) },
    ];
  });
  return [
    notice(),
    heading(2, 'Summary'),
    paragraph(`${sorted.length} file(s) in the ${feedName} feed.`),
    table(['File', 'Table', 'Rows', 'Columns', 'TBD fields', 'PII columns', 'PCI columns', 'Lint errors'], rows),
    ...(delivery
      ? [heading(2, 'Delivery'), `<p>Jira epic: ${delivery.epicUrl ? externalLink(delivery.epicKey, delivery.epicUrl) : delivery.epicKey}</p>`]
      : []),
    ...(exports.length
      ? [heading(2, 'Exports'), paragraph('Generated from this spec and attached to this page. They update automatically when the spec changes.'),
         `<ul>${exports.map((e) => `<li>${attachmentLink(e.name)}: ${escapeXml(e.description)}</li>`).join('')}</ul>`]
      : []),
    heading(2, 'File specs'),
    childrenMacro(),
    heading(2, 'How to read the spec tables'),
    legend(),
  ].join('');
}

export function renderFilePage(feedName: string, spec: FileSpec): string {
  const cols = [...spec.columns].sort((a, b) => a.position - b.position);
  const pk = cols.find((c) => c.primaryKey.value);
  const rows = cols.map((c: ColumnSpec): Cell[] => [
    { text: String(c.position + 1) },
    { text: c.sourceName, code: true },
    cell(c.targetName, (v) => v, true),
    cell(c.type, (v) => formatType(v), true),
    cell(c.nullable, (v) => (v === null ? 'TBD' : v ? 'Yes' : 'No')),
    cell(c.primaryKey, (v) => (v ? 'PK' : '')),
    cell(c.pii, (v) => (v ? `${v.classification}${v.category ? ` (${v.category.replace(/_/g, ' ')})` : ''}` : 'TBD')),
    cell(c.description, (v) => v ?? 'TBD'),
  ]);
  const parts = [
    notice(),
    heading(2, 'Overview'),
    paragraph(`Feed: ${feedName}. Source file: ${spec.fileName}. Target table: ${spec.tableName.value}. Rows profiled: ${spec.rowCount.toLocaleString('en-US')}. Primary key: ${pk ? pk.targetName.value : 'none identified'}.`),
    heading(2, 'Columns'),
    table(['#', 'Source column', 'Target name', 'Type', 'Nullable', 'Key', 'Classification', 'Description'], rows),
  ];
  if (spec.findings.length > 0) {
    parts.push(heading(2, 'Open findings'), bulletList(spec.findings.map((f) => `[${f.severity}] ${f.column ? `${f.column}: ` : ''}${f.message}`)));
  }
  parts.push(heading(3, 'Legend'), legend());
  return parts.join('');
}
